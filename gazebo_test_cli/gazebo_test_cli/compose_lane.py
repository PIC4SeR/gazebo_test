"""A lane as a Docker Compose project: one service per :class:`LaneWindow`.

``ros2 gazeboexp run ... --backend compose --lane-dir DIR`` writes
``DIR/compose.yaml`` (and ``DIR/lane.json``, the spec it came from) and starts
nothing; ``docker/lane.sh`` (or the dashboard's compose backend) then runs

    docker compose -p lane-<domain> -f DIR/compose.yaml up --exit-code-from manager

Every service runs the same image, on the project's own network, with the data
root bind-mounted at the same path as on the host, so paths written by one
service (rendered Nav2 params, results, bags) are valid in every other one and
on the host. The world file stays private to the ``sim`` container.

The services wait for ``sim`` to be healthy (``clock_ready``: /clock advances)
instead of starting together as tmux windows do.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any, Dict, List

import yaml

from gazebo_test_cli.lane_spec import LaneSpec

DEFAULT_IMAGE = "gt-lane:latest"
# Sources ROS and the workspaces, then execs its arguments (docker/entrypoint.sh
# in the image). A healthcheck does not go through the image's ENTRYPOINT, so
# it calls the entrypoint explicitly.
ENTRYPOINT = "/usr/local/bin/gt-entrypoint"
# Roles that make no sense without a display: never started in compose.
SKIPPED_ROLES = ("rviz",)


def project_name(domain: int) -> str:
    return f"lane-{domain}"


def service_names(spec: LaneSpec) -> List[str]:
    """Service name per window, in start order (extras numbered)."""
    names: List[str] = []
    extra = 0
    for window in spec.windows:
        if window.role in SKIPPED_ROLES:
            continue
        if window.role == "extra":
            extra += 1
            names.append(f"extra-{extra}")
        else:
            names.append(window.role)
    return names


def render_compose(spec: LaneSpec, *, data_root: str, image: str = DEFAULT_IMAGE,
                   lane_dir: str = "") -> Dict[str, Any]:
    """The compose document (a dict) for ``spec``."""
    data_root = str(Path(data_root).resolve())
    env = {
        **spec.env,
        "GT_DATA": data_root,
        # The lane root inside each container (private world file of sim).
        "GAZEBO_TEST_LANE_DIR": f"/tmp/gazebo_test_{spec.domain}",
    }

    def service(command: str, extra_env: Dict[str, str] = None) -> Dict[str, Any]:
        body: Dict[str, Any] = {
            "image": image,
            "command": ["bash", "-c", command.strip()],
            "environment": {**env, **(extra_env or {})},
            "volumes": [f"{data_root}:{data_root}"],
            "init": True,  # reap launch's children; forward SIGTERM on down
            "stop_grace_period": "20s",
        }
        return body

    services: Dict[str, Any] = {}
    healthy_sim = {"sim": {"condition": "service_healthy"}}
    windows = [w for w in spec.windows if w.role not in SKIPPED_ROLES]
    for name, window in zip(service_names(spec), windows):
        if window.role == "sim":
            body = service(window.command, {"GT_XVFB": "1"})
            body["shm_size"] = "1gb"
            body["healthcheck"] = {
                "test": ["CMD", ENTRYPOINT, "ros2", "run", "gazebo_test", "clock_ready",
                         "--timeout", "4"],
                "interval": "5s",
                "timeout": "15s",
                "retries": 3,
                "start_period": "180s",
            }
        else:
            body = service(window.command)
            body["depends_on"] = healthy_sim
        services[name] = body
    manager = service(spec.manager.command)
    manager["depends_on"] = healthy_sim
    services["manager"] = manager

    document: Dict[str, Any] = {
        "name": project_name(spec.domain),
        "services": services,
    }
    if lane_dir:
        document["x-gazebo-test"] = {"lane_dir": str(lane_dir), "experiment": spec.experiment,
                                     "algorithm": spec.algorithm}
    return document


def write_lane(spec: LaneSpec, lane_dir: Path, *, data_root: str,
               image: str = DEFAULT_IMAGE) -> Path:
    """Write ``compose.yaml`` and ``lane.json`` into ``lane_dir``; returns the compose file."""
    lane_dir = Path(lane_dir)
    data = Path(data_root).resolve()
    if data != lane_dir.resolve() and data not in lane_dir.resolve().parents:
        raise ValueError(f"lane dir {lane_dir} must be inside the data root {data}")
    lane_dir.mkdir(parents=True, exist_ok=True)
    document = render_compose(spec, data_root=str(data), image=image, lane_dir=str(lane_dir))
    compose_file = lane_dir / "compose.yaml"
    compose_file.write_text(
        "# Generated by `ros2 gazeboexp run --backend compose`; do not edit.\n"
        + yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=4096))
    (lane_dir / "lane.json").write_text(json.dumps(asdict(spec), indent=1) + "\n")
    return compose_file
